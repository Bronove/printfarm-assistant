# 意图判据：必须看**原文**（归一化会把"改成/调成/设置"当废话删掉）
WANT_CHANGE = re.compile(r'改|调|设|换|写|变成|弄成|搞成')
ASK_WHERE = re.compile(r'在哪|哪里|怎么找|怎么调|教|位置|找不到|在哪一页')
ASK_ABOUT = re.compile(r'是什么|什么意思|作用|区别|建议|多少合适|要不要')


def wants_change(text):
    """用户是不是想改参数（拿原文判断）。"""
    return bool(WANT_CHANGE.search(text or ''))


def asks_where(text):
    """用户是不是在问"在哪"（拿原文判断）。"""
    return bool(ASK_WHERE.search(text or ''))


def asks_about(text):
    """用户是不是在问"这是什么/有什么区别"。"""
    return bool(ASK_ABOUT.search(text or ''))


def normalize(text):
    """语音输入归一化：同音纠正、口语简化、中文数字转阿拉伯、
    去语气词/废话、合并重复，输出尽量干净的参数描述。"""
    t = text or ''
    for src, dst in VOICE_MAP:
        t = t.replace(src, dst)
    # 模糊数量："两三个"→"3个""五六个"→"6个"（取大）
    t = re.sub(r'(一|两|三|四|五|六|七|八|九)(两|三|四|五|六|七|八|九)个',
               lambda m: f'{_CN_DIGITS[m.group(2)]}个', t)
    # 中文数字 → 阿拉伯（限定上下文，避免误伤）
    t = re.sub(r'百分之([零一二两三四五六七八九十百]+)',
               lambda m: f'{cn_num(m.group(1))}%', t)
    t = re.sub(r'(层高|层厚)\s*([零一二两三四五六七八九十点]+)',
               lambda m: f'{m.group(1)}{cn_num(m.group(2))}', t)
    t = re.sub(r'(填充|密度)\s*([零一二两三四五六七八九十点]+)',
               lambda m: f'{m.group(1)}{cn_num(m.group(2))}', t)
    t = re.sub(r'打印\s*([零一二两三四五六七八九十]+)\s*个',
               lambda m: f'打{cn_num(m.group(1))}个', t)
    t = re.sub(r'(打|克隆|复制|要|切|切出)\s*'
               r'([零一二两三四五六七八九十]+)\s*个',
               lambda m: f'{m.group(1)}{cn_num(m.group(2))}个', t)
    # 参数后面跟中文数字（不限百分比）：喷嘴温度两百四 → 喷嘴温度240
    t = re.sub(r'(温度|速度|加速度|流量|厚度|宽度|高度|长度|距离|间距|'
               r'角度|倍率|层数|圈数|个数|分钟|小时|秒|度|毫米|克)'
               r'\s*([零一二两三四五六七八九十百点]+)',
               lambda m: f'{m.group(1)}{cn_num(m.group(2))}', t)
    # "填充50%"要认成"填充密度50%"（只带数字的"填充"就是密度，不是图案/速度）
    t = re.sub(r'填充(?!密度|图案|速度|方向|互锁|合并|最小)\s*(\d)',
               r'填充密度\1', t)
    t = re.sub(r'([a-zA-Z])\s*([零一二两三四五六七八九])\s*([a-zA-Z])',
               lambda m: f'{m.group(1).lower()}{_CN_DIGITS[m.group(2)]}'
                         f'{m.group(3).lower()}', t)
    t = re.sub(r'(\d)\s*点\s*(\d+)', r'\1.\2', t)
    # 明确不要支撑 → 无支撑（放在去语气词之前，保证"不用支撑"等）
    t = re.sub(r'(?:不\s*(?:要|用|需要)?\s*开?|别\s*开?|不要开|'
               r'不用开|不开|关\s*(?:掉|闭)?|关闭|取消|去掉|去除|'
               r'撤掉|移除|弄掉|删掉|免)'
               r'\s*(?:树状|树形|树枝|树支|普通|正常)?\s*支撑',
               '无支撑', t)
    # "支撑去掉/支撑给去掉/支撑不要了/把支撑弄掉"等支撑在后的说法
    t = re.sub(r'(?:树状|树形|树枝|树支|普通|正常)?\s*支撑\s*'
               r'(?:给|都|就|也|先|再|还)?\s*'
               r'(?:去掉|去除|不要了|不要|不用|不需要|取消|关掉|关闭|'
               r'撤掉|撤了|去了|移除|别要|不弄|别弄|不弄了|弄掉|删掉|'
               r'关了|没了|免|不开|别开|不要开|不用开)'
               r'(?!\s*(?:碰|压|接触|重叠|贴|挨|到模型|到本体))'
               r'(?:了|吧|的|一下|就好|就行|哈)?',
               '无支撑', t)
    # 3D 蜂窝：3d蜂窝/三维蜂窝/蜂窝3d → 统一成 3d蜂窝
    t = re.sub(r'3\s*d\s*蜂窝|三维蜂窝|蜂窝\s*3\s*d|蜂窝3d',
               '3d蜂窝', t, flags=re.I)
    # 材料同音：碳钎维→碳纤维、pet g/pet-g→petg
    t = re.sub(r'pet[\s\-]?g', 'petg', t, flags=re.I)
    # 去掉标点和多余符号，只留中文、字母数字、% . - / 空格
    t = re.sub(r'[^\w\u4e00-\u9fff%. \-/]+', ' ', t)
    # 清除语气词/废话（可反复多轮，直到稳定）
    for _ in range(5):
        before = t
        for f in VOICE_FILLERS:
            if f in t:
                t = t.replace(f, '')
        if t == before:
            break
    # 合并中文重复（"填充填充"→"填充""嗯嗯"→"嗯"）
    t = re.sub(r'([\u4e00-\u9fff]{1,4})\1+', r'\1', t)
    t = re.sub(r'\s+', ' ', t).strip()
    return t
