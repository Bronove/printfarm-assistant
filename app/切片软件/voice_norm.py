"""语音/口语归一化：**两个形态共用同一份**。

第一形态（切片软件）把它用在参数需求输入框上，第二形态（挂件）用在气泡
输入框上——两边说的是同一批人话，表就不该有两份：

  * 语音识别同音字：树支/树枝/竖状/数状 → 树状；添充/甜充 → 填充；
    曾高/层厚 → 层高；风窝/蜂巢 → 蜂窝；裸旋 → 螺旋；克龙 → 克隆；
    拼判/拼版 → 摆盘；紧促/紧奏 → 紧凑；碳钎维 → 碳纤维……
  * 语气词/废话：麻烦你帮我、我想要、就是、的话、把、吧……
  * 中文数字 → 阿拉伯：零点二 → 0.2、百分之五十 → 50%、打八个 → 打8个
  * 材料同音：pet / ptg / pet g / pet-g → petg
  * 整句改判："不要支撑 / 把支撑去掉" → `无支撑`（不是"支撑+否定"）
  * 3D 蜂窝的几种说法归一

**归一化会删掉"改成/调成/设置"这类词**，所以"用户是不是要改参数"必须拿
**原文**判断——这就是 wants_change() / asks_where() 放在这里的原因，
免得两个形态各写一套正则、行为不一致。
"""

import re

_CN_DIGITS = {'零': 0, '一': 1, '二': 2, '两': 2, '三': 3, '四': 4,
              '五': 5, '六': 6, '七': 7, '八': 8, '九': 9}


def cn_num(s):
    """中文数字转阿拉伯：零点二→0.2、二十三→23、百分之五十→50。

    口语的"两百四"要说成 240（不是 204）——"两百零四"才是 204。
    语音输入里这两种都会出现，靠有没有"零/十"来分辨。
    """
    s = (s or '').strip()
    if not s:
        return ''
    if '点' in s:
        a, b = s.split('点', 1)
        ia = cn_num(a)
        fb = ''.join(str(_CN_DIGITS.get(ch, 0)) for ch in b)
        if ia == '' or ia == 0:
            return f'0.{fb}'
        return f'{ia}.{fb}'
    if '百' in s:
        a, b = s.split('百', 1)
        ia = cn_num(a) or 1
        base = ia * 100
        if not b:
            return base
        if b.startswith('零'):
            return base + (cn_num(b[1:]) or 0)
        if '十' not in b and len(b) == 1:
            return base + _CN_DIGITS.get(b, 0) * 10      # 两百四 → 240
        return base + (cn_num(b) or 0)
    if '十' in s:
        a, b = s.split('十', 1)
        ia = cn_num(a) or 1
        return ia * 10 + (cn_num(b) or 0)
    total = 0
    for ch in s:
        total = total * 10 + _CN_DIGITS.get(ch, 0)
    return total


